import type { DemoCostLine, DemoState } from "./demoTypes";

export interface DemoCostSummary {
  additionsSubtotal: number | null;
  deductionsSubtotal: number | null;
  subtotal: number | null;
  taxAmount: number | null;
  totalAmount: number | null;
  missingCount: number;
  calculableCount: number;
}

function toPaise(amount: number): number {
  return Math.round(amount * 100);
}

function fromPaise(paise: number): number {
  return Math.round(paise) / 100;
}

/** Deterministic integer-paise cost calculation (never substitutes missing inputs with zero). */
export function computeDemoCostSummary(
  lines: DemoCostLine[],
  taxPercent: number | null
): DemoCostSummary {
  let additionsPaise = 0;
  let deductionsPaise = 0;
  let calculableCount = 0;
  let missingCount = 0;

  for (const line of lines) {
    if (line.quantity === null || line.rate === null) {
      missingCount += 1;
      continue;
    }
    const linePaise = Math.round(line.quantity * line.rate * 100);
    if (line.lineType === "deduction") {
      deductionsPaise += linePaise;
    } else {
      additionsPaise += linePaise;
    }
    calculableCount += 1;
  }

  if (calculableCount === 0) {
    return {
      additionsSubtotal: null,
      deductionsSubtotal: null,
      subtotal: null,
      taxAmount: null,
      totalAmount: null,
      missingCount,
      calculableCount,
    };
  }

  const netPaise = additionsPaise - deductionsPaise;
  const taxPaise =
    taxPercent !== null ? Math.round((netPaise * taxPercent) / 100) : 0;

  return {
    additionsSubtotal: fromPaise(additionsPaise),
    deductionsSubtotal: fromPaise(deductionsPaise),
    subtotal: fromPaise(netPaise),
    taxAmount: taxPercent !== null ? fromPaise(taxPaise) : null,
    totalAmount: fromPaise(netPaise + taxPaise),
    missingCount,
    calculableCount,
  };
}

export function computeLineAmount(line: DemoCostLine): number | null {
  if (line.quantity === null || line.rate === null) return null;
  const raw = fromPaise(toPaise(line.quantity * line.rate));
  return line.lineType === "deduction" ? -raw : raw;
}

export function formatInr(amount: number | null | undefined, fallback = "—"): string {
  if (amount === null || amount === undefined || Number.isNaN(amount)) {
    return fallback;
  }
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount);
}

